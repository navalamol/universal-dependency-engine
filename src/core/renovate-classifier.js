'use strict';

const semver = require('semver');

const CATEGORIES = {
  COVERED_PHASE_A:          'COVERED_PHASE_A',
  COVERED_PHASE_B:          'COVERED_PHASE_B',
  DISCARDED_MAJOR_BUMP:     'DISCARDED_MAJOR_BUMP',
  DISCARDED_MULTI_MAJOR:    'DISCARDED_MULTI_MAJOR',
  DISCARDED_NO_FIX:         'DISCARDED_NO_FIX',
  RENOVATE_INSUFFICIENT:    'RENOVATE_INSUFFICIENT',
  NOT_IN_MEND_REPORT:       'NOT_IN_MEND_REPORT',
  MONOREPO_GROUP_UPDATE:    'MONOREPO_GROUP_UPDATE',
};

// Phase rank for picking the "best" item when a package has multiple entries (multi-version conflict).
const PHASE_RANK = { A: 3, B: 2, C: 1 };

/**
 * Extract package name and proposed version from a Renovate PR title.
 *
 * Handles:
 *   "Update dependency axios to v1.8.4"
 *   "chore(deps): update dependency socket.io-parser to v4.2.4"
 *   "Update @babel/core to v7.26.0"
 *   "fix(deps): Update @scope/pkg to 3.1.0"
 *   "[NEUTRAL] Update dependency jsdoc-to-markdown to v6.0.1 (dev)"
 *   "Replace dependency npm-run-all with npm-run-all2 ^5.0.0 (dev)"
 *   "Update babel monorepo (dev)"
 */
function parsePRTitleNew(title) {
  // Monorepo group update — no target version in the title
  // e.g. "Update babel monorepo (dev)"
  const monoMatch = title.match(
    /update\s+((?:@[\w.-]+\/)?[\w.-]+)\s+monorepo/i
  );
  if (monoMatch) {
    return { packageName: monoMatch[1], isMonorepoGroup: true, proposedVersion: null };
  }

  // Package group update with a target version — Renovate batches related packages
  // e.g. "Update socket.io packages to v4.8.3 (dev)"
  const pkgGroupMatch = title.match(
    /update\s+((?:@[\w.-]+\/)?[\w.-]+)\s+packages\s+to\s+[v^]?(\d+\.\d+(?:\.\d+)?(?:-[\w.]+)?)/i
  );
  if (pkgGroupMatch) {
    const version = semver.valid(semver.coerce(pkgGroupMatch[2]));
    if (!version) return null;
    return { packageName: pkgGroupMatch[1], proposedVersion: version, isPackageGroup: true };
  }

  // "Update dependency <pkg> to v<ver>" — prefix tags like [NEUTRAL] are ignored (regex not anchored)
  const updateMatch = title.match(
    /update\s+(?:dependency\s+)?((?:@[\w.-]+\/)?[\w.-]+)\s+to\s+v?(\d+\.\d+(?:\.\d+)?(?:-[\w.]+)?)/i
  );

  // "Replace dependency <old> with <new> ^<ver>" — handles both v and ^ version prefixes
  const replaceMatch = title.match(
    /replace\s+dependency\s+((?:@[\w.-]+\/)?[\w.-]+)\s+with\s+((?:@[\w.-]+\/)?[\w.-]+)\s+[v^]?(\d+\.\d+(?:\.\d+)?(?:-[\w.]+)?)/i
  );

  if (updateMatch) {
    const version = semver.valid(semver.coerce(updateMatch[2]));
    if (!version) return null;
    return { packageName: updateMatch[1], proposedVersion: version };
  }

  if (replaceMatch) {
    const version = semver.valid(semver.coerce(replaceMatch[3]));
    if (!version) return null;
    return { oldPackageName: replaceMatch[1], packageName: replaceMatch[2], proposedVersion: version };
  }

  return null;
}

/**
 * Build a comment body for a classified PR.
 */
function buildCloseComment(classified) {
  const { category, parsed, phasedItem } = classified;
  const pkg = parsed ? parsed.packageName : '(unknown)';
  const renovateV = parsed ? parsed.proposedVersion : '?';
  const cveList = phasedItem ? phasedItem.cves.map(c => c.id).join(', ') : '';
  const mendV = phasedItem ? phasedItem.recommendedVersion : '?';

  if (category === CATEGORIES.COVERED_PHASE_A) {
    return [
      `This upgrade is covered by mendfix Phase A (safe same-major security fix).`,
      ``,
      `mendfix recommends: ${pkg}@${mendV}`,
      `Renovate proposed:  ${pkg}@${renovateV}`,
      `CVEs addressed: ${cveList || 'see Mend report'}`,
      ``,
      `This PR has been closed automatically. The fix will be applied via package.json overrides by mendfix (Phase A — auto-applicable, no breaking changes).`,
    ].join('\n');
  }

  if (category === CATEGORIES.COVERED_PHASE_B) {
    return [
      `This upgrade is covered by mendfix Phase B (security fix — requires review before applying).`,
      ``,
      `mendfix recommends: ${pkg}@${mendV}`,
      `Renovate proposed:  ${pkg}@${renovateV}`,
      `CVEs addressed: ${cveList || 'see Mend report'}`,
      ``,
      `This PR has been closed automatically. The fix is tracked in phase-b-overrides.json and requires team review before applying (multiple version lines detected in the dependency tree).`,
    ].join('\n');
  }

  if (category === CATEGORIES.DISCARDED_MAJOR_BUMP) {
    const from = phasedItem ? phasedItem.currentVersion : '?';
    return [
      `mendfix classifies this as a MAJOR_BUMP (Phase C).`,
      ``,
      `Renovate proposes: ${pkg} ${from} -> ${renovateV}`,
      `CVEs: ${cveList || 'see Mend report'}`,
      ``,
      `This upgrade requires manual compatibility review before merging. A major version jump may introduce breaking API changes. See manual-review.md generated by mendfix for the full justification and required action checklist.`,
    ].join('\n');
  }

  if (category === CATEGORIES.MONOREPO_GROUP_UPDATE) {
    const group = parsed ? parsed.packageName : '(unknown)';
    return [
      `This is a monorepo group update for "${group}".`,
      ``,
      `No specific target version was found in the PR title. mendfix cannot auto-classify or apply monorepo group updates — manual review is required.`,
      ``,
      `Check each package in the group individually and apply upgrades via mendfix analyze/apply once the group packages appear in a Mend vulnerability report.`,
    ].join('\n');
  }

  if (category === CATEGORIES.DISCARDED_MULTI_MAJOR) {
    return [
      `mendfix classifies this as a multi-major conflict (Phase C).`,
      ``,
      `Renovate proposes: ${pkg} -> ${renovateV}`,
      ``,
      `Multiple major version lines of this package exist in the dependency tree. A single overrides entry cannot safely pin all copies without nested parent overrides. This requires manual dependency tree analysis before applying.`,
      ``,
      `See manual-review.md generated by mendfix for the full justification and required action checklist.`,
    ].join('\n');
  }

  if (category === CATEGORIES.DISCARDED_NO_FIX) {
    return [
      `mendfix was unable to identify a safe fix version for ${pkg} (Phase C — NO_FIX).`,
      ``,
      `Renovate proposed: ${pkg} -> ${renovateV}`,
      `CVEs: ${cveList || 'see Mend report'}`,
      ``,
      `No fixed version was found in the vulnerability report for the current major version line. Manual review is required to determine if this package can be upgraded or replaced.`,
    ].join('\n');
  }

  if (category === CATEGORIES.RENOVATE_INSUFFICIENT) {
    return [
      `mendfix could not confidently classify this Renovate PR for ${pkg}.`,
      ``,
      `Renovate proposed: ${pkg} -> ${renovateV}`,
      ``,
      `The PR title did not contain enough version information to map against the mendfix remediation plan. Manual review is required.`,
    ].join('\n');
  }

  if (category === CATEGORIES.NOT_IN_MEND_REPORT) {
    return [
      `${pkg} is not present in the current Mend vulnerability report.`,
      ``,
      `Renovate proposed: ${pkg} -> ${renovateV}`,
      ``,
      `This upgrade is a routine maintenance update, not a security fix tracked by Mend. Review according to your team's standard upgrade policy.`,
    ].join('\n');
  }

  return '';
}

/**
 * Classify each Renovate PR against the mendfix phased analysis results.
 *
 * @param {object[]} renovatePRs  - from github.fetchRenovatePRs()
 * @param {object[]} phasedItems  - from phases.applyPhases()
 * @returns {object[]} classified PR records
 */
function classifyPRs(renovatePRs, phasedItems) {
  // Index by library name — a package may have multiple entries (multi-version conflict)
  const byName = new Map();
  for (const item of phasedItems) {
    if (!byName.has(item.libraryName)) byName.set(item.libraryName, []);
    byName.get(item.libraryName).push(item);
  }

  return renovatePRs.map(pr => {
    const parsed = parsePRTitleNew(pr.title);

    if (!parsed) {
      return {
        pr,
        parsed: null,
        category: CATEGORIES.NOT_IN_MEND_REPORT,
        reason: 'Could not parse package name from PR title — not a standard Renovate format or not package-related.',
      };
    }

    if (parsed.isMonorepoGroup) {
      return {
        pr, parsed,
        category: CATEGORIES.MONOREPO_GROUP_UPDATE,
        reason: `Monorepo group update for "${parsed.packageName}" — no specific version in PR title; manual assessment required.`,
      };
    }

    const { packageName, proposedVersion, oldPackageName } = parsed;
    // Replace PRs: check new package name first, then old (it may be in the Mend report under the old name)
    const items = byName.get(packageName) || (oldPackageName ? byName.get(oldPackageName) : null) || [];

    if (items.length === 0) {
      return {
        pr,
        parsed,
        category: CATEGORIES.NOT_IN_MEND_REPORT,
        reason: `${packageName} is not in the Mend vulnerability report for this repo.`,
      };
    }

    // When multiple entries exist (multi-major conflict), pick the highest-phase item.
    // Phase A beats B beats C — if any item is Phase A, that determines the outcome.
    const primaryItem = items
      .slice()
      .sort((a, b) => (PHASE_RANK[b.phase] || 0) - (PHASE_RANK[a.phase] || 0))[0];

    const requiredVersion = primaryItem.recommendedVersion;

    if (primaryItem.phase === 'C') {
      if (primaryItem.upgradeType === 'MAJOR_BUMP') {
        return {
          pr, parsed, phasedItem: primaryItem,
          category: CATEGORIES.DISCARDED_MAJOR_BUMP,
          reason: `mendfix Phase C / MAJOR_BUMP: ${packageName} ${primaryItem.currentVersion} -> ${requiredVersion}. Needs manual compatibility check.`,
        };
      }
      if (primaryItem.upgradeType === 'SAFE') {
        // Multi-major conflict — multiple major version lines exist in the dependency tree.
        // A flat override cannot safely cover both; requires manual nested overrides.
        return {
          pr, parsed, phasedItem: primaryItem,
          category: CATEGORIES.DISCARDED_MULTI_MAJOR,
          reason: `mendfix Phase C / multi-major conflict: ${packageName} has multiple major version lines in the tree. Flat override is unsafe — manual nested overrides required.`,
        };
      }
      return {
        pr, parsed, phasedItem: primaryItem,
        category: CATEGORIES.DISCARDED_NO_FIX,
        reason: `No published fix available for ${packageName}@${primaryItem.currentVersion}.`,
      };
    }

    // Phase A or B — check whether Renovate's version satisfies the minimum security fix
    if (requiredVersion && semver.valid(proposedVersion) && semver.valid(requiredVersion)) {
      if (!semver.gte(proposedVersion, requiredVersion)) {
        return {
          pr, parsed, phasedItem: primaryItem,
          category: CATEGORIES.RENOVATE_INSUFFICIENT,
          reason: `Renovate proposes ${packageName}@${proposedVersion} but the CVE fix requires >= ${requiredVersion}.`,
        };
      }
    }

    if (primaryItem.phase === 'A') {
      return {
        pr, parsed, phasedItem: primaryItem,
        category: CATEGORIES.COVERED_PHASE_A,
        reason: `mendfix Phase A handles ${packageName} via safe same-major override (${primaryItem.currentVersion} -> ${requiredVersion}).`,
      };
    }

    return {
      pr, parsed, phasedItem: primaryItem,
      category: CATEGORIES.COVERED_PHASE_B,
      reason: `mendfix Phase B handles ${packageName} (multiple version lines — review before applying).`,
    };
  });
}

/**
 * Summarise counts by category for a set of classified PRs.
 */
function summarize(classifiedPRs) {
  const counts = {
    total: classifiedPRs.length,
    coveredA: 0,
    coveredB: 0,
    majorBump: 0,
    multiMajor: 0,
    noFix: 0,
    insufficient: 0,
    notInReport: 0,
    monoRepoGroup: 0,
  };
  for (const c of classifiedPRs) {
    if (c.category === CATEGORIES.COVERED_PHASE_A)            counts.coveredA++;
    else if (c.category === CATEGORIES.COVERED_PHASE_B)       counts.coveredB++;
    else if (c.category === CATEGORIES.DISCARDED_MAJOR_BUMP)  counts.majorBump++;
    else if (c.category === CATEGORIES.DISCARDED_MULTI_MAJOR) counts.multiMajor++;
    else if (c.category === CATEGORIES.DISCARDED_NO_FIX)      counts.noFix++;
    else if (c.category === CATEGORIES.RENOVATE_INSUFFICIENT) counts.insufficient++;
    else if (c.category === CATEGORIES.NOT_IN_MEND_REPORT)    counts.notInReport++;
    else if (c.category === CATEGORIES.MONOREPO_GROUP_UPDATE) counts.monoRepoGroup++;
  }
  return counts;
}

/**
 * Analyze relationships between classified Renovate PRs.
 *
 * Detects:
 *  - redundantPRs: PRs whose direct upgrade becomes unnecessary when a parent-upgrade PR merges.
 *    E.g., PR-B upgrades X directly; PR-A upgrades parent Y which transitively fixes X → PR-B is redundant.
 *  - chainGroups: sets of PRs that affect packages in the same dependency chain.
 *  - orderedMerge: recommended merge order (parent upgrades before direct child upgrades).
 *
 * @param {object[]} classifiedPRs  — output of classifyPRs()
 * @param {object[]} phasedItems    — output of applyPhases()
 * @returns {{
 *   redundantPRs: Array<{ redundantPR, supersededBy, reason }>,
 *   chainGroups:  Array<{ packages: string[], prs: object[] }>,
 *   orderedMerge: Array<{ pr, order: number, note: string }>,
 * }}
 */
function analyzePRRelationships(classifiedPRs, phasedItems) {
  // Index phasedItems by library name for O(1) lookup
  const byPkg = new Map();
  for (const item of phasedItems) {
    byPkg.set(item.libraryName, item);
  }

  // ── Redundancy detection ──────────────────────────────────────────────────
  // PR-B directly upgrades child package X.
  // PR-A upgrades parent Y → its parentUpgradePaths covers X.
  // → PR-B is redundant when PR-A is merged.
  const redundantPRs = [];

  for (const pr of classifiedPRs) {
    if (!pr.parsed || pr.parsed.isMonorepoGroup) continue;
    const childPkg = pr.parsed.packageName;
    const childItem = byPkg.get(childPkg);

    // Skip if the child has no finding or has no parent upgrade path
    if (!childItem || !childItem.parentUpgradePaths || childItem.parentUpgradePaths.length === 0) continue;

    // Find other PRs in this set that upgrade the parent
    for (const parentPath of childItem.parentUpgradePaths) {
      const parentName = parentPath.parent;
      const parentPR   = classifiedPRs.find(
        p => p !== pr && p.parsed && p.parsed.packageName === parentName
      );
      if (parentPR) {
        redundantPRs.push({
          redundantPR:  pr,
          supersededBy: parentPR,
          reason:       `Upgrading ${parentName} (PR #${parentPR.pr.number || '?'}) transitively fixes ${childPkg}. ` +
                        `Direct upgrade PR #${pr.pr.number || '?'} is redundant once the parent PR merges.`,
        });
      }
    }
  }

  // ── Chain grouping ────────────────────────────────────────────────────────
  // Group PRs that touch packages in the same parent→child chains.
  const grouped = _groupByChain(classifiedPRs, phasedItems, byPkg);

  // ── Merge order ───────────────────────────────────────────────────────────
  // Parent upgrades should merge before direct child upgrades in the same chain.
  const orderedMerge = _buildMergeOrder(classifiedPRs, phasedItems, byPkg);

  return { redundantPRs, chainGroups: grouped, orderedMerge };
}

function _groupByChain(classifiedPRs, phasedItems, byPkg) {
  // Build a chain-membership map: pkg → chain IDs it participates in
  const chainOf = new Map();  // pkgName → set of chainIds
  let chainId   = 0;

  for (const item of phasedItems) {
    if (!item.parentUpgradePaths || item.parentUpgradePaths.length === 0) continue;
    for (const path of item.parentUpgradePaths) {
      const id  = chainId++;
      const set = new Set([item.libraryName, path.parent, ...(path.chainVia || [])]);
      for (const pkg of set) {
        if (!chainOf.has(pkg)) chainOf.set(pkg, new Set());
        chainOf.get(pkg).add(id);
      }
    }
  }

  // For each PR, find which chain(s) its package belongs to
  const chainToPRs = new Map();
  for (const pr of classifiedPRs) {
    if (!pr.parsed || pr.parsed.isMonorepoGroup) continue;
    const pkg    = pr.parsed.packageName;
    const chains = chainOf.get(pkg) || new Set();
    for (const id of chains) {
      if (!chainToPRs.has(id)) chainToPRs.set(id, { packages: new Set(), prs: [] });
      chainToPRs.get(id).packages.add(pkg);
      chainToPRs.get(id).prs.push(pr);
    }
  }

  // Only emit groups with more than one PR
  return [...chainToPRs.values()]
    .filter(g => g.prs.length > 1)
    .map(g => ({ packages: [...g.packages], prs: g.prs }));
}

function _buildMergeOrder(classifiedPRs, phasedItems, byPkg) {
  // Parent upgrade PRs go first (order 1); direct child upgrades go second (order 2);
  // unrelated PRs get order 3.
  const parentUpgradeTargets = new Set(
    phasedItems.flatMap(i => (i.parentUpgradePaths || []).map(p => p.parent))
  );

  return classifiedPRs
    .filter(pr => pr.parsed && !pr.parsed.isMonorepoGroup)
    .map(pr => {
      const pkg   = pr.parsed.packageName;
      const item  = byPkg.get(pkg);
      const isParentUpgradePR = parentUpgradeTargets.has(pkg);
      const isDirectChildPR   = item && item.parentUpgradePaths && item.parentUpgradePaths.length > 0;

      if (isParentUpgradePR) {
        return { pr, order: 1, note: `Parent upgrade — merge first; transitively fixes dependent vulnerabilities` };
      }
      if (isDirectChildPR) {
        return { pr, order: 2, note: `Direct child upgrade — can be replaced by a parent upgrade if one exists` };
      }
      return { pr, order: 3, note: `Independent upgrade — no ordering constraint` };
    })
    .sort((a, b) => a.order - b.order);
}

module.exports = { CATEGORIES, parsePRTitleNew, classifyPRs, summarize, buildCloseComment, analyzePRRelationships };
