'use strict';

const semver = require('semver');

const CATEGORIES = {
  COVERED_PHASE_A:          'COVERED_PHASE_A',
  COVERED_PHASE_B:          'COVERED_PHASE_B',
  DISCARDED_MAJOR_BUMP:     'DISCARDED_MAJOR_BUMP',
  DISCARDED_MULTI_MAJOR:    'DISCARDED_MULTI_MAJOR',
  DISCARDED_NO_FIX:         'DISCARDED_NO_FIX',
  RENOVATE_INSUFFICIENT:    'RENOVATE_INSUFFICIENT',
  NOT_IN_MEND_REPORT:       'NOT_IN_MEND_REPORT',
};

// Phase rank for picking the "best" item when a package has multiple entries (multi-version conflict).
const PHASE_RANK = { A: 3, B: 2, C: 1 };

/**
 * Extract package name and proposed version from a Renovate PR title.
 *
 * Handles:
 *   "Update dependency axios to v1.8.4"
 *   "chore(deps): update dependency socket.io-parser to v4.2.4"
 *   "Update @babel/core to v7.26.0"
 *   "fix(deps): Update @scope/pkg to 3.1.0"
 */
function parsePRTitle(title) {
  // Scoped (@scope/pkg) or unscoped package name, then "to v{semver}"
  const match = title.match(
    /(?:update\s+(?:dependency\s+)?)((?:@[\w.-]+\/)?[\w.-]+)\s+to\s+v?(\d+\.\d+(?:\.\d+)*(?:-[\w.]+)?)/i
  );
  if (!match) return null;
  const version = semver.valid(semver.coerce(match[2]));
  if (!version) return null;
  return { packageName: match[1], proposedVersion: version };
}

/**
 * Build a comment body for a classified PR.
 */
function buildCloseComment(classified) {
  const { category, parsed, phasedItem } = classified;
  const pkg = parsed ? parsed.packageName : '(unknown)';
  const renovateV = parsed ? parsed.proposedVersion : '?';
  const cveList = phasedItem ? phasedItem.cves.map(c => c.id).join(', ') : '';
  const mendV = phasedItem ? phasedItem.recommendedVersion : '?';

  if (category === CATEGORIES.COVERED_PHASE_A) {
    return [
      `This upgrade is covered by mendfix Phase A (safe same-major security fix).`,
      ``,
      `mendfix recommends: ${pkg}@${mendV}`,
      `Renovate proposed:  ${pkg}@${renovateV}`,
      `CVEs addressed: ${cveList || 'see Mend report'}`,
      ``,
      `This PR has been closed automatically. The fix will be applied via package.json overrides by mendfix (Phase A — auto-applicable, no breaking changes).`,
    ].join('\n');
  }

  if (category === CATEGORIES.COVERED_PHASE_B) {
    return [
      `This upgrade is covered by mendfix Phase B (security fix — requires review before applying).`,
      ``,
      `mendfix recommends: ${pkg}@${mendV}`,
      `Renovate proposed:  ${pkg}@${renovateV}`,
      `CVEs addressed: ${cveList || 'see Mend report'}`,
      ``,
      `This PR has been closed automatically. The fix is tracked in phase-b-overrides.json and requires team review before applying (multiple version lines detected in the dependency tree).`,
    ].join('\n');
  }

  if (category === CATEGORIES.DISCARDED_MAJOR_BUMP) {
    const from = phasedItem ? phasedItem.currentVersion : '?';
    return [
      `mendfix classifies this as a MAJOR_BUMP (Phase C).`,
      ``,
      `Renovate proposes: ${pkg} ${from} -> ${renovateV}`,
      `CVEs: ${cveList || 'see Mend report'}`,
      ``,
      `This upgrade requires manual compatibility review before merging. A major version jump may introduce breaking API changes. See manual-review.md generated by mendfix for the full justification and required action checklist.`,
    ].join('\n');
  }

  return '';
}

/**
 * Classify each Renovate PR against the mendfix phased analysis results.
 *
 * @param {object[]} renovatePRs  - from github.fetchRenovatePRs()
 * @param {object[]} phasedItems  - from phases.applyPhases()
 * @returns {object[]} classified PR records
 */
function classifyPRs(renovatePRs, phasedItems) {
  // Index by library name — a package may have multiple entries (multi-version conflict)
  const byName = new Map();
  for (const item of phasedItems) {
    if (!byName.has(item.libraryName)) byName.set(item.libraryName, []);
    byName.get(item.libraryName).push(item);
  }

  return renovatePRs.map(pr => {
    const parsed = parsePRTitle(pr.title);

    if (!parsed) {
      return {
        pr,
        parsed: null,
        category: CATEGORIES.NOT_IN_MEND_REPORT,
        reason: 'Could not parse package name from PR title — not a standard Renovate format or not package-related.',
      };
    }

    const { packageName, proposedVersion } = parsed;
    const items = byName.get(packageName) || [];

    if (items.length === 0) {
      return {
        pr,
        parsed,
        category: CATEGORIES.NOT_IN_MEND_REPORT,
        reason: `${packageName} is not in the Mend vulnerability report for this repo.`,
      };
    }

    // When multiple entries exist (multi-major conflict), pick the highest-phase item.
    // Phase A beats B beats C — if any item is Phase A, that determines the outcome.
    const primaryItem = items
      .slice()
      .sort((a, b) => (PHASE_RANK[b.phase] || 0) - (PHASE_RANK[a.phase] || 0))[0];

    const requiredVersion = primaryItem.recommendedVersion;

    if (primaryItem.phase === 'C') {
      if (primaryItem.upgradeType === 'MAJOR_BUMP') {
        return {
          pr, parsed, phasedItem: primaryItem,
          category: CATEGORIES.DISCARDED_MAJOR_BUMP,
          reason: `mendfix Phase C / MAJOR_BUMP: ${packageName} ${primaryItem.currentVersion} -> ${requiredVersion}. Needs manual compatibility check.`,
        };
      }
      if (primaryItem.upgradeType === 'SAFE') {
        // Multi-major conflict — multiple major version lines exist in the dependency tree.
        // A flat override cannot safely cover both; requires manual nested overrides.
        return {
          pr, parsed, phasedItem: primaryItem,
          category: CATEGORIES.DISCARDED_MULTI_MAJOR,
          reason: `mendfix Phase C / multi-major conflict: ${packageName} has multiple major version lines in the tree. Flat override is unsafe — manual nested overrides required.`,
        };
      }
      return {
        pr, parsed, phasedItem: primaryItem,
        category: CATEGORIES.DISCARDED_NO_FIX,
        reason: `No published fix available for ${packageName}@${primaryItem.currentVersion}.`,
      };
    }

    // Phase A or B — check whether Renovate's version satisfies the minimum security fix
    if (requiredVersion && semver.valid(proposedVersion) && semver.valid(requiredVersion)) {
      if (!semver.gte(proposedVersion, requiredVersion)) {
        return {
          pr, parsed, phasedItem: primaryItem,
          category: CATEGORIES.RENOVATE_INSUFFICIENT,
          reason: `Renovate proposes ${packageName}@${proposedVersion} but the CVE fix requires >= ${requiredVersion}.`,
        };
      }
    }

    if (primaryItem.phase === 'A') {
      return {
        pr, parsed, phasedItem: primaryItem,
        category: CATEGORIES.COVERED_PHASE_A,
        reason: `mendfix Phase A handles ${packageName} via safe same-major override (${primaryItem.currentVersion} -> ${requiredVersion}).`,
      };
    }

    return {
      pr, parsed, phasedItem: primaryItem,
      category: CATEGORIES.COVERED_PHASE_B,
      reason: `mendfix Phase B handles ${packageName} (multiple version lines — review before applying).`,
    };
  });
}

/**
 * Summarise counts by category for a set of classified PRs.
 */
function summarize(classifiedPRs) {
  const counts = {
    total: classifiedPRs.length,
    coveredA: 0,
    coveredB: 0,
    majorBump: 0,
    multiMajor: 0,
    noFix: 0,
    insufficient: 0,
    notInReport: 0,
  };
  for (const c of classifiedPRs) {
    if (c.category === CATEGORIES.COVERED_PHASE_A)           counts.coveredA++;
    else if (c.category === CATEGORIES.COVERED_PHASE_B)      counts.coveredB++;
    else if (c.category === CATEGORIES.DISCARDED_MAJOR_BUMP) counts.majorBump++;
    else if (c.category === CATEGORIES.DISCARDED_MULTI_MAJOR) counts.multiMajor++;
    else if (c.category === CATEGORIES.DISCARDED_NO_FIX)      counts.noFix++;
    else if (c.category === CATEGORIES.RENOVATE_INSUFFICIENT) counts.insufficient++;
    else if (c.category === CATEGORIES.NOT_IN_MEND_REPORT)    counts.notInReport++;
  }
  return counts;
}

module.exports = { CATEGORIES, parsePRTitle, classifyPRs, summarize, buildCloseComment };
