'use strict';

/**
 * Scenario 18: Generate a PR-ready description summarising the mendfix remediation run.
 *
 * @param {object[]} phasedPlan  - output of applyPhases()
 * @param {object}   reportMeta  - { project, reportDate, ecosystem, verifyVersions }
 * @returns {string} markdown
 */
function generatePRDescription(phasedPlan, reportMeta) {
  const { project, reportDate, ecosystem } = reportMeta || {};
  const phaseA = phasedPlan.filter(i => i.phase === 'A');
  const phaseB = phasedPlan.filter(i => i.phase === 'B');
  const phaseC = phasedPlan.filter(i => i.phase === 'C' && !i.probableFalsePositive);
  const fps    = phasedPlan.filter(i => i.probableFalsePositive);

  const allCves = phasedPlan.flatMap(i => i.cves || []);
  const bySeverity = { CRITICAL: 0, HIGH: 0, MEDIUM: 0, LOW: 0, UNKNOWN: 0 };
  for (const cve of allCves) {
    const sev = (cve.severity || 'UNKNOWN').toUpperCase();
    if (sev in bySeverity) bySeverity[sev]++;
    else bySeverity.UNKNOWN++;
  }

  const lines = [
    `## Security Remediation — ${project || 'Mend Report'}`,
    ``,
    `**Date:** ${reportDate || '(unknown)'}  `,
    `**Ecosystem:** ${ecosystem || 'npm'}  `,
    `**Total CVEs:** ${allCves.length} (Critical: ${bySeverity.CRITICAL} | High: ${bySeverity.HIGH} | Medium: ${bySeverity.MEDIUM} | Low: ${bySeverity.LOW})`,
    ``,
    `### Phase A — Auto-applied (${phaseA.length} packages)`,
    ``,
    `High confidence same-major upgrades applied as \`overrides\` or direct dependency bumps.`,
    ``,
  ];

  if (phaseA.length > 0) {
    lines.push('| Package | Current | Fix | Type |');
    lines.push('|---------|---------|-----|------|');
    for (const item of phaseA) {
      const type = item._directUpgrade ? 'direct' : 'override';
      lines.push(`| \`${item.libraryName}\` | ${item.currentVersion} | **${item.recommendedVersion}** | ${type} |`);
    }
    lines.push('');
  } else {
    lines.push('_No Phase A items._', '');
  }

  if (phaseB.length > 0) {
    lines.push(`### Phase B — Requires Reviewer Action (${phaseB.length} packages)`, '');
    lines.push('These overrides were written but require team review before merging.', '');
    lines.push('| Package | Current | Fix | Reason |');
    lines.push('|---------|---------|-----|--------|');
    for (const item of phaseB) {
      const reason = item.rangeViolation
        ? `Consumer \`${item.rangeViolation.consumer}\` pins \`${item.rangeViolation.range}\``
        : item.justification.slice(0, 80);
      lines.push(`| \`${item.libraryName}\` | ${item.currentVersion} | ${item.recommendedVersion} | ${reason} |`);
    }
    lines.push('');
  }

  if (phaseC.length > 0) {
    lines.push(`### Phase C — Manual Review Required (${phaseC.length} packages)`, '');
    lines.push('NOT applied. See `manual-review.md` for required action checklist.', '');
    for (const item of phaseC) {
      const fix = item.recommendedVersion || 'NO FIX';
      lines.push(`- **${item.libraryName}** ${item.currentVersion} → ${fix} [${item.upgradeType}]: ${item.justification}`);
    }
    lines.push('');
  }

  if (fps.length > 0) {
    lines.push(`### Probable False Positives (${fps.length} packages)`, '');
    lines.push('All dependency chains are dev/build-only. No override applied.', '');
    for (const item of fps) {
      lines.push(`- **${item.libraryName}** ${item.currentVersion}: ${item.justification}`);
    }
    lines.push('');
  }

  lines.push('---');
  lines.push('_Generated by [mend-autofixer](https://github.com/your-org/universal-dependency-engine). Review `phase-a-overrides.json` before merging._');

  return lines.join('\n');
}

module.exports = { generatePRDescription };
